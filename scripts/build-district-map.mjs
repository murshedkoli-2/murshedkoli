#!/usr/bin/env node
/**
 * Converts Bangladesh district (ADM2) boundaries into compact SVG paths.
 *
 * Source data: geoBoundaries gbOpen BGD ADM2 (simplified), from the Bangladesh
 * Bureau of Statistics / OCHA ROAP, licensed CC BY 3.0 IGO.
 *   https://www.geoboundaries.org/api/current/gbOpen/BGD/ADM2/
 *
 * Usage:
 *   node scripts/build-district-map.mjs <path-to-geoBoundaries-BGD-ADM2_simplified.geojson>
 *
 * Writes lib/data/bd-district-paths.ts. Re-run only when the boundaries change.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const WIDTH = 600
const PAD = 8
const SIMPLIFY_PX = 0.7
const MIN_RING_AREA_PX = 6

// geoBoundaries spellings → ids in lib/data/bd-districts.ts
const ALIASES = {
  barisal: 'barishal', bogra: 'bogura', brahamanbaria: 'brahmanbaria', chittagong: 'chattogram',
  comilla: 'cumilla', jessore: 'jashore', jhalokati: 'jhalokathi', maulvibazar: 'moulvibazar',
  nawabganj: 'chapai-nawabganj', netrakona: 'netrokona', "cox's-bazar": 'coxs-bazar',
}

const toId = (name) => {
  const slug = name.trim().toLowerCase().replace(/\s+/g, '-')
  return ALIASES[slug] ?? slug.replace(/[^a-z-]/g, '')
}

const input = process.argv[2]
if (!input) {
  console.error('Pass the path to the ADM2 GeoJSON file.')
  process.exit(1)
}
const geo = JSON.parse(readFileSync(input, 'utf8'))

const polygonsOf = (g) => (g.type === 'Polygon' ? [g.coordinates] : g.type === 'MultiPolygon' ? g.coordinates : [])

let minLon = Infinity, maxLon = -Infinity, minLat = Infinity, maxLat = -Infinity
for (const f of geo.features) for (const poly of polygonsOf(f.geometry)) for (const ring of poly) for (const [lon, lat] of ring) {
  minLon = Math.min(minLon, lon); maxLon = Math.max(maxLon, lon)
  minLat = Math.min(minLat, lat); maxLat = Math.max(maxLat, lat)
}

const kx = Math.cos(((minLat + maxLat) / 2) * Math.PI / 180)
const scale = (WIDTH - PAD * 2) / ((maxLon - minLon) * kx)
const HEIGHT = Math.ceil((maxLat - minLat) * scale + PAD * 2)
const project = ([lon, lat]) => [PAD + (lon - minLon) * kx * scale, PAD + (maxLat - lat) * scale]

function perpendicular(p, a, b) {
  const dx = b[0] - a[0], dy = b[1] - a[1]
  if (dx === 0 && dy === 0) return Math.hypot(p[0] - a[0], p[1] - a[1])
  return Math.abs(dy * p[0] - dx * p[1] + b[0] * a[1] - b[1] * a[0]) / Math.hypot(dx, dy)
}

function simplify(points, tolerance) {
  if (points.length < 3) return points
  let maxDist = 0, index = 0
  for (let i = 1; i < points.length - 1; i++) {
    const d = perpendicular(points[i], points[0], points[points.length - 1])
    if (d > maxDist) { maxDist = d; index = i }
  }
  if (maxDist <= tolerance) return [points[0], points[points.length - 1]]
  return [...simplify(points.slice(0, index + 1), tolerance).slice(0, -1), ...simplify(points.slice(index), tolerance)]
}

const area = (ring) => {
  let a = 0
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) a += (ring[j][0] + ring[i][0]) * (ring[j][1] - ring[i][1])
  return a / 2
}

function centroid(ring) {
  let x = 0, y = 0, a = 0
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const f = ring[j][0] * ring[i][1] - ring[i][0] * ring[j][1]
    x += (ring[j][0] + ring[i][0]) * f; y += (ring[j][1] + ring[i][1]) * f; a += f
  }
  return a === 0 ? ring[0] : [x / (3 * a), y / (3 * a)]
}

const r1 = (n) => Math.round(n * 10) / 10
const out = {}
for (const f of geo.features) {
  const id = toId(f.properties.shapeName)
  let d = '', largest = null, largestArea = 0
  for (const poly of polygonsOf(f.geometry)) {
    poly.forEach((ring, ringIndex) => {
      const pts = simplify(ring.map(project), SIMPLIFY_PX)
      const ringArea = Math.abs(area(pts))
      if (pts.length < 4 || ringArea < MIN_RING_AREA_PX) return
      if (ringIndex === 0 && ringArea > largestArea) { largestArea = ringArea; largest = pts }
      d += 'M' + pts.slice(0, -1).map(([x, y]) => `${r1(x)} ${r1(y)}`).join('L') + 'Z'
    })
  }
  const [cx, cy] = centroid(largest)
  out[id] = { d, cx: r1(cx), cy: r1(cy) }
}

const ids = Object.keys(out).sort()
if (ids.length !== 64) throw new Error(`Expected 64 districts, got ${ids.length}`)

const target = join(dirname(fileURLToPath(import.meta.url)), '..', 'lib', 'data', 'bd-district-paths.ts')
const body = ids.map((id) => `  ${JSON.stringify(id)}: ${JSON.stringify(out[id])},`).join('\n')
writeFileSync(target, `// Generated by scripts/build-district-map.mjs — do not edit by hand.
// Boundaries: geoBoundaries gbOpen BGD ADM2 (BBS / OCHA ROAP), CC BY 3.0 IGO.

export interface DistrictShape { d: string; cx: number; cy: number }

export const BD_MAP_VIEWBOX = '0 0 ${WIDTH} ${HEIGHT}'

export const BD_DISTRICT_SHAPES: Record<string, DistrictShape> = {
${body}
}
`)
console.log(`Wrote ${ids.length} districts to ${target}`)
